"""JSON Schemas for the agent protocol, generated from the pydantic models.

The files under ``schemas/`` in the repository are generated by this module and a test
checks they match the models. After changing ``models.py``, regenerate them with::

    python -m ccfoundry_agent_kit.schemas schemas/
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from .models import AgentManifest, ChatRequest, ChatResponse

SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"

SCHEMA_MODELS: dict[str, type[BaseModel]] = {
    "agent-manifest.schema.json": AgentManifest,
    "chat-request.schema.json": ChatRequest,
    "chat-response.schema.json": ChatResponse,
}


def build_schema(model: type[BaseModel]) -> dict[str, Any]:
    return {"$schema": SCHEMA_DIALECT, **model.model_json_schema()}


def render_schema(model: type[BaseModel]) -> str:
    return json.dumps(build_schema(model), indent=2, ensure_ascii=False) + "\n"


def write_schemas(directory: str | Path) -> list[Path]:
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for filename, model in SCHEMA_MODELS.items():
        path = target / filename
        path.write_text(render_schema(model), encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    for path in write_schemas(args[0] if args else "schemas"):
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
